// Manual browser regression. Run only in an isolated DSH_HOME; creates a uniquely named test project.
async page => {
 const projectName='UI 回归 '+Date.now();
 const root=page.locator('[data-task-manager]');
 if(!await root.isVisible())await page.getByRole('button',{name:'任务管理',exact:true}).click();
 await root.waitFor();
 const uiState=async()=>await page.evaluate(async()=>{const r=await(await fetch('/api/mt-tasks',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({endpoint:'snapshot'})})).json();if(!r.ok)throw Error(JSON.stringify(r));return r.value;});
 const mutate=async(op,action,title)=>{const response=page.waitForResponse(r=>{if(!r.url().endsWith('/api/mt-tasks'))return false;const d=r.request().postDataJSON();return d.endpoint==='mutate'&&d.payload.op===op&&(!title||d.payload.args.title===title);});await action();const reply=await(await response).json();if(!reply.ok)throw Error(JSON.stringify(reply));return reply.value.state;};
 const assert=(condition,msg)=>{if(!condition)throw Error(msg);};
 const results=[];
 await page.waitForFunction(()=>{const button=document.querySelector('.mtt-project-add');return button&&!button.disabled;});
 await root.getByRole('navigation',{name:'任务导航',exact:true}).getByRole('button',{name:'新建项目',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'新建项目',exact:true});
 await dialog.getByRole('textbox',{name:'项目名称',exact:true}).fill(projectName);
 await mutate('project.create',()=>dialog.getByRole('button',{name:'保存',exact:true}).click());
 await root.getByRole('heading',{name:projectName,exact:true}).waitFor();
 const composer=root.getByRole('form',{name:'添加任务',exact:true});
 await composer.waitFor();
 await composer.getByRole('textbox',{name:'任务名称',exact:true}).fill('梳理本周计划');
 await mutate('task.create',()=>composer.getByRole('textbox',{name:'任务名称',exact:true}).press('Enter'),'梳理本周计划');
 await composer.getByRole('textbox',{name:'任务名称',exact:true}).fill('发送周报');
 await mutate('task.create',()=>composer.getByRole('textbox',{name:'任务名称',exact:true}).press('Enter'),'发送周报');
 await composer.getByRole('button',{name:'取消',exact:true}).click();
 assert(await root.getByRole('heading',{level:1}).count()===1,'Duplicate heading');
 assert(!await root.locator('.mtt-tools').isVisible(),'Composer did not close');
 results.push('新建项目直接进入，回车连续创建，单一标题和可收起输入');
 const card=root.locator('.mtt-card').filter({has:page.getByRole('button',{name:'梳理本周计划',exact:true})});
 await card.getByRole('button',{name:'梳理本周计划',exact:true}).click();
 const detail=root.getByRole('complementary',{name:'任务详情',exact:true});
 await detail.waitFor();
 await detail.getByRole('textbox',{name:'任务名称',exact:true}).fill('梳理本周计划');
 await detail.getByRole('textbox',{name:'备注',exact:true}).fill('先整理本周安排，再分配下一步工作。');
 await detail.getByRole('textbox',{name:'添加子任务',exact:true}).fill('整理会议记录');
 const childState=await mutate('task.create',()=>detail.getByRole('textbox',{name:'添加子任务',exact:true}).press('Enter'),'整理会议记录');
 const projectId=childState.projects.find(p=>p.name===projectName).id;
 const parent=childState.tasks.find(t=>t.title==='梳理本周计划'&&t.projectId===projectId);
 assert(parent.notes==='先整理本周安排，再分配下一步工作。','Dirty notes lost before child creation');
 assert(childState.tasks.some(t=>t.parentId===parent.id&&t.title==='整理会议记录'),'Child missing');
 assert(!await root.getByRole('alert').isVisible(),'Conflict after dirty child creation');
 results.push('备注未保存时添加子任务会先保存，不再版本冲突');
 let releaseFirst;
 const firstHeld=new Promise(resolve=>{releaseFirst=resolve;});
 let firstSeenResolve;
 const firstSeen=new Promise(resolve=>{firstSeenResolve=resolve;});
 await page.route('**/api/mt-tasks',async route=>{
   const d=route.request().postDataJSON();
   if(d?.endpoint==='mutate'&&d.payload.op==='task.update'&&d.payload.args.notes==='保存期间的第一版'){
     firstSeenResolve();await firstHeld;
   }
   await route.continue();
 });
 await detail.getByRole('textbox',{name:'备注',exact:true}).fill('保存期间的第一版');
 await detail.locator('.mtt-detail-heading').click();
 await firstSeen;
 await detail.getByRole('textbox',{name:'备注',exact:true}).fill('保存期间继续输入的最终版');
 const secondSaved=page.waitForResponse(r=>{if(!r.url().endsWith('/api/mt-tasks'))return false;const d=r.request().postDataJSON();return d.endpoint==='mutate'&&d.payload.args.notes==='保存期间继续输入的最终版';});
 releaseFirst();
 const savedReply=await(await secondSaved).json();
 assert(savedReply.ok,'Second save failed');
 assert(savedReply.value.state.tasks.find(t=>t.id===parent.id).notes==='保存期间继续输入的最终版','New typing overwritten');
 assert(await detail.getByRole('textbox',{name:'备注',exact:true}).inputValue()==='保存期间继续输入的最终版','Visible input overwritten');
 await page.unroute('**/api/mt-tasks');
 results.push('延迟保存请求期间继续输入，最终版本保持且落盘');
 // Closing or navigating must flush edits before changing the selected task.
 await detail.getByRole('textbox',{name:'备注',exact:true}).fill('最终备注：准备议程、整理会议记录、确认负责人。');
 await detail.getByRole('button',{name:'关闭',exact:true}).click();
 await detail.waitFor({state:'hidden'});
 const persisted=await uiState();
 assert(persisted.tasks.find(t=>t.id===parent.id).notes==='最终备注：准备议程、整理会议记录、确认负责人。','Close lost draft');
 results.push('关闭详情前自动保存编辑');
 const child=card.locator('.mtt-child').filter({has:page.getByRole('button',{name:'整理会议记录',exact:true})});
 await child.getByRole('button',{name:'整理会议记录',exact:true}).click({button:'right'});
 const popup=page.locator('[popover]:popover-open');
 assert((await popup.getAttribute('aria-label')).includes('整理会议记录'),'Child opened parent context menu');
 await page.keyboard.press('Escape');
 assert(await root.isVisible(),'Escape closed host plugin');
 await root.getByRole('complementary',{name:'任务详情'}).waitFor({state:'hidden'});
 await mutate('task.update',()=>child.getByRole('checkbox',{name:'整理会议记录',exact:true}).click());
 assert(!await card.getByRole('checkbox',{name:'标记完成',exact:true}).isChecked(),'Child completed parent');
 results.push('子任务右键菜单归属正确，Esc 只关闭菜单，子任务独立完成');
 await root.getByRole('button',{name:'搜索任务',exact:true}).click();
 const search=root.getByRole('searchbox',{name:'搜索任务',exact:true});
 await search.fill('整理会议记录');
 await root.locator('.mtt-content > article').waitFor();
 assert(await root.locator('.mtt-content > article').count()===1,'Child search did not preserve one parent');
 assert(await root.locator('.mtt-content').getByRole('button',{name:'梳理本周计划',exact:true}).isVisible(),'Child search missing context');
 await search.fill('不存在的回归词');
 await root.getByText('没有匹配的任务',{exact:true}).waitFor();
 await root.getByRole('button',{name:'清除筛选',exact:true}).last().click();
 await root.getByRole('search',{name:'筛选任务',exact:true}).getByRole('button',{name:'关闭',exact:true}).click();
 results.push('搜索子任务时保留主任务上下文，无结果可清除');
 const report=root.locator('.mtt-card').filter({has:page.getByRole('button',{name:'发送周报',exact:true})});
 await mutate('task.update',()=>report.getByRole('checkbox',{name:'标记完成',exact:true}).click());
 const completed=root.locator('.mtt-completed-section');
 await completed.getByRole('button',{name:'发送周报',exact:true}).waitFor();
 assert(await completed.locator('time').count()>0,'Completion time missing');
 await root.getByRole('button',{name:'已完成 1',exact:true}).click();
 assert(!await completed.getByRole('button',{name:'发送周报',exact:true}).isVisible(),'Completed collapse failed');
 await root.getByRole('button',{name:'已完成 1',exact:true}).press('Enter');
 await completed.getByRole('button',{name:'发送周报',exact:true}).waitFor();
 results.push('完成项沉底、记录时间、完成分组鼠标和键盘展开折叠');
 await root.getByRole('button',{name:'收起导航',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.mtt-projects').getBoundingClientRect().width<=60);
 assert(await root.locator('.mtt-content').getByRole('button',{name:'梳理本周计划',exact:true}).isVisible(),'Compact nav changed scope');
 await root.getByRole('button',{name:'展开导航',exact:true}).click();
 await page.locator('body').click({position:{x:2,y:2}});
 await page.keyboard.press('Shift+A');
 await composer.waitFor();
 await composer.getByRole('textbox',{name:'任务名称',exact:true}).press('Escape');
 assert(!await composer.isVisible(),'Escape did not close task input');
 assert(await root.isVisible(),'Escape closed plugin');
 results.push('导航紧凑模式、Shift+A 与 Esc 可用');
 await root.screenshot({path:'/tmp/dsh-task-manager-ui-workflows.png',animations:'disabled'});
 return {project:projectName,parentId:parent.id,results};
}
