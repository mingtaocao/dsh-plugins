import test from 'node:test';
import assert from 'node:assert/strict';
import { extractDocument, decodeEntities, collapseWhitespace } from '../lib/parse.js';

test('entities and whitespace', () => {
  assert.equal(decodeEntities('a &amp; b &lt;c&gt; &#20320;&#22909; &nbsp;x'), 'a & b <c> 你好 \u00a0x');
  assert.equal(collapseWhitespace('  a\n\n b\t c  '), 'a b c');
});

test('title prefers h1, collects headings, skips script/style/svg/hidden', () => {
  const html = `<!doctype html><html><head><title>文档标题</title>
    <style>.x{content:"样式里的词"}</style></head>
    <body>
      <h1>一级标题 &amp; 副标题</h1>
      <h2>小标题一</h2>
      <p>正文第一段，包含中文关键词：缓存一致性。</p>
      <script>const secret = "脚本里的秘密词条";</script>
      <svg><text>图表坐标文字</text></svg>
      <div hidden>隐藏属性文本</div>
      <div aria-hidden="true">无障碍隐藏文本</div>
      <div style="display:none">display none 文本</div>
      <h3>小标题二</h3>
      <p>正文第二段。</p>
    </body></html>`;

  const doc = extractDocument(html, { fallbackTitle: 'fallback' });
  assert.equal(doc.title, '一级标题 & 副标题');
  assert.deepEqual(doc.headings, ['一级标题 & 副标题', '小标题一', '小标题二']);
  assert.match(doc.text, /缓存一致性/);
  assert.ok(!doc.text.includes('秘密词条'));
  assert.ok(!doc.text.includes('样式里的词'));
  assert.ok(!doc.text.includes('图表坐标文字'));
  assert.ok(!doc.text.includes('隐藏属性文本'));
  assert.ok(!doc.text.includes('无障碍隐藏文本'));
  assert.ok(!doc.text.includes('display none 文本'));
  assert.ok(doc.excerpt.length <= 220);
});

test('title falls back to <title> and then to the caller name', () => {
  const withTitle = extractDocument('<html><head><title>来自 title</title></head><body><p>正文</p></body></html>');
  assert.equal(withTitle.title, '来自 title');

  const withoutTitle = extractDocument('<html><body><p>正文而已</p></body></html>', { fallbackTitle: '文件名' });
  assert.equal(withoutTitle.title, '文件名');

  const empty = extractDocument('', { fallbackTitle: '' });
  assert.equal(empty.title, '未命名文档');
});

test('excerpt is taken from the first substantial paragraph', () => {
  const long = '这是一段很长的正文。'.repeat(40);
  const doc = extractDocument(`<html><body><h1>标题</h1><p>${long}</p></body></html>`);
  assert.ok(doc.excerpt.length > 0 && doc.excerpt.length <= 220);
  assert.ok(long.startsWith(doc.excerpt.slice(0, 12)));
});

test('text length cap keeps indexing bounded', () => {
  const huge = `<html><body><h1>大文件</h1><p>${'字'.repeat(5000)}</p></body></html>`;
  const doc = extractDocument(huge, { maxTextLength: 500 });
  assert.equal(doc.text.length, 500);
});


test('h2 cannot replace h1 and meta description supplies the excerpt', () => {
  const doc = extractDocument(`<head><title>Page title</title><meta content="文档简介 &amp; 更多" name="description"></head>
    <body><h2>Navigation</h2><h1>Article</h1><p>这是正文内容，用于验证摘要回退。</p></body>`);
  assert.equal(doc.title, 'Article');
  assert.equal(doc.excerpt, '文档简介 & 更多');
  const fallback = extractDocument('<title>Page title</title><h2>Section</h2>');
  assert.equal(fallback.title, 'Page title');
});


test('excerpt uses document content instead of generator attribution and section labels', () => {
  const doc = extractDocument(`<body><p>Generated by Answer me with HTML 0.5.11 · 2026-11-12</p>
    <h1>知识库体验</h1><p>Runtime note</p><h2>正文</h2><p>这才是文档的内容简介，应该出现在列表摘要。</p></body>`);
  assert.equal(doc.excerpt, '这才是文档的内容简介，应该出现在列表摘要。');
  const meta = extractDocument(`<meta name="description" content="Generated by Some Tool"><h1>标题</h1><p>可用于检索的实际正文内容。</p>`);
  assert.equal(meta.excerpt, '可用于检索的实际正文内容。');
});
